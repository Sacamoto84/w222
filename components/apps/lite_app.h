#pragma once

#include "lvgl.h"

// Базовый класс для небольших приложений, которые запускаются через LiteLauncher.
//
// Каждый экран-приложение наследуется от LiteApp и описывает:
// - как оно выглядит в лаунчере: title(), icon_text(), accent_color();
// - как оно инициализируется и открывает свой интерфейс: init(), open();
// - как оно реагирует на кнопку "назад" и закрытие: back(), close().
//
// LiteLauncher хранит указатели на LiteApp, показывает их иконки на главном экране,
// а при открытии передает приложению LVGL-контейнер parent. Приложение должно
// создавать свои LVGL-объекты внутри этого parent и очищать свои ресурсы в close().
class LiteApp {
public:
    // Callback, через который приложение может попросить лаунчер закрыть себя.
    // app указывает на приложение, которое отправило запрос, user_ctx обычно
    // содержит указатель на LiteLauncher или другой внешний контекст.
    using CloseRequestCallback = void (*)(LiteApp *app, void *user_ctx);

    // Виртуальный деструктор нужен, чтобы наследники корректно уничтожались
    // через указатель на LiteApp.
    virtual ~LiteApp() = default;

    // Текстовое название приложения. Лаунчер показывает его под иконкой
    // и в заголовке открытого приложения.
    virtual const char *title(void) const = 0;

    // Текст или LVGL-символ внутри иконки на главном экране лаунчера.
    // Например, "C" для калькулятора или LV_SYMBOL_SETTINGS для настроек.
    virtual const char *icon_text(void) const = 0;

    // Основной цвет приложения. Лаунчер использует его как фон иконки
    // и цвет тени, чтобы визуально отличать приложения друг от друга.
    virtual lv_color_t accent_color(void) const = 0;

    // Если приложение само размещает кнопку назад и хочет занять весь экран,
    // оно может скрыть верхний заголовок LiteLauncher.
    virtual bool use_launcher_header(void) const { return true; }

    // Однократная инициализация приложения перед первым open().
    // LiteLauncher вызывает init() только при первом открытии конкретного
    // приложения. Верните false, если приложение не готово к запуску.
    virtual bool init(void) { return true; }

    // Открывает приложение и строит его интерфейс внутри parent.
    //
    // parent - это контейнер лаунчера для тела приложения. Наследник обычно
    // создает в нем один корневой LVGL-объект, а уже внутри него всю остальную UI.
    // Верните false, если интерфейс не удалось создать; лаунчер закроет приложение.
    virtual bool open(lv_obj_t *parent) = 0;

    // Обработка действия "назад": кнопка в заголовке или жест вправо.
    //
    // Верните true, если приложение само обработало возврат, например закрыло
    // внутренний экран или диалог. Верните false, чтобы LiteLauncher закрыл
    // приложение и вернулся на главный экран.
    virtual bool back(void) { return false; }

    // Закрытие приложения. LiteLauncher вызывает close() перед возвратом
    // на главный экран или перед открытием другого приложения.
    //
    // Здесь нужно остановить таймеры, отписаться от внешних событий и освободить
    // app-local ресурсы. LVGL-объекты внутри parent лаунчер затем очищает сам.
    virtual void close(void) {}

    // LiteLauncher устанавливает этот callback при открытии приложения.
    // Наследникам обычно не нужно вызывать этот метод напрямую.
    void set_close_request_callback(CloseRequestCallback callback, void *user_ctx)
    {
        close_request_callback_ = callback;
        close_request_user_ctx_ = user_ctx;
    }

protected:
    // Позволяет приложению закрыть себя изнутри.
    //
    // Пример: пользователь нажал кнопку "Закрыть" внутри приложения или операция
    // завершилась, и экран больше не нужен. Метод не закрывает UI напрямую,
    // а отправляет запрос владельцу через callback, чтобы закрытие прошло через
    // общий жизненный цикл LiteLauncher: close(), очистка parent, возврат домой.
    void request_close(void)
    {
        if (close_request_callback_ != nullptr) {
            close_request_callback_(this, close_request_user_ctx_);
        }
    }

private:
    // Сохраненные callback и пользовательский контекст для request_close().
    // Когда приложение закрывается, LiteLauncher сбрасывает их в nullptr.
    CloseRequestCallback close_request_callback_ = nullptr;
    void *close_request_user_ctx_ = nullptr;
};
