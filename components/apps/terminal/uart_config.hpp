#pragma once

// Общая конфигурация UART терминала.
//
// И приложение терминала (потребитель байтового потока), и приложение
// "Настройки UART" работают с одной и той же конфигурацией. Значения хранятся
// в NVS; при первом запуске (нет записи) берутся значения по умолчанию из
// Kconfig (sdkconfig). После сохранения выставляется флаг "грязно", который
// UART-задача терминала вычитывает и применяет к живому драйверу.

namespace uartcfg {

// Чётность кадра. Значения совпадают по смыслу с uart_parity_t, но модуль
// host-safe и не тянет драйвер UART в заголовок.
enum class Parity : int {
    None = 0,
    Even = 1,
    Odd = 2,
};

struct Config {
    int port = 1;            // номер контроллера UART (0..2)
    int rx_pin = 35;         // GPIO приёма (-1 = отключён)
    int tx_pin = -1;         // GPIO передачи (-1 = не используется)
    int baud = 115200;       // скорость, бод
    Parity parity = Parity::None;
};

// Значения по умолчанию из Kconfig.
Config defaults();

// Загрузить конфигурацию из NVS; при отсутствии записи вернуть defaults().
Config load();

// Сохранить конфигурацию в NVS и выставить флаг "грязно" для терминала.
// Возвращает true при успешной записи.
bool save(const Config &cfg);

// Вернуть true ровно один раз после каждого save() (сбрасывает флаг).
// Терминал опрашивает этот флаг в своей UART-задаче и переинициализирует порт.
bool consume_dirty();

}  // namespace uartcfg
