/** \brief Быстрая аппроксимация синуса заданного угла
 *
 * \paramangle_degreesУгол в градусах
 * \return Синус заданного угла
 *
 */
float nema_sin(float angle_degrees);


/** \brief Быстрая аппроксимация заданного угла косинуса
 *
 * \paramangle_degreesУгол в градусах
 * \return Косинус заданного угла
 *
 */
float nema_cos(float angle_degrees);

/** \brief Быстрая касательная аппроксимация заданного угла
 *
 * \paramangle_degreesУгол в градусах
 * \return Тангенс заданного угла
 *
 */
float nema_tan(float angle_degrees);


/** \brief Быстрая аппроксимация синуса заданного угла
 *
 * \paramangle_radiansУгол в радианах
 * \return Синус заданного угла
 *
 */
float nema_sin_r(float angle_radians);


/** \brief Быстрая аппроксимация заданного угла косинуса
 *
 * \paramangle_radiansУгол в радианах
 * \return Косинус заданного угла
 *
 */
float nema_cos_r(float angle_radians);

/** \brief Быстрая касательная аппроксимация заданного угла
 *
 * \paramangle_radiansУгол в радианах
 * \return Тангенс заданного угла
 *
 */
float nema_tan_r(float angle_radians);

/** \brief Быстрая арктангенсальная аппроксимация г/х
 *
 * \параметр y значение
 * \параметр x значение
 * \return Арктангенс заданного г/х в градусах
 *
 */
