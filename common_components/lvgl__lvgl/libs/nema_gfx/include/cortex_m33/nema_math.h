/** \brief Аппроксимация обратного тангенса x с плавающей запятой
 *
 * \param x значение X
 * \return Обратный тангенс (уголь) x в градусах
 *
 */
float nema_atan(float x);

/** \brief Найдите минимум два измерения
 *
 * \param Первое значение
 * \param b Второе значение
 * \return Минимум a и b
 *
 */
#define nema_min2(a,b) (((a)<(b))?( a):(b))

/** \brief Определите максимум двух результатов
 *
 * \param Первое значение
 * \param b Второе значение
 * \return Максимум a и b
 *
 */
#define nema_max2(a,b) (((a)>(b))?( a):(b))

/** \brief Значение клеммы
 *
 * \param val Значение для фиксации
 * \param min Минимальное значение
 * \param max Минимальное значение
 * \return Зафиксированное значение
 *
 */
#define nema_clamp(val, min, max) nema_min2((max), nema_max2((min), (val)))

/** \brief Вычислить абсолютное значение int
 *
 * \параметр значение
 * \return Абсолютное значение
 *
 */
#define nema_abs(a)    (((a)< 0 )?(-(a)):(a))

/** \brief Вычислить абсолютное значение числа с плавающей запятой
 *
 * \параметр значение
 * \return Абсолютное значение
 *
 */
#define nema_absf(a)    (((a)< 0.f )?(-(a)):(a))


/** \brief Сравнение двух чисел с плавающей запятой
 *
 * \param x Первое число с плавающей запятой
 * \param y число Второе с плавающей запятой
 * \return 1, если x == y, 0, если x != y
 *
 */
#define nema_floats_equal(x, y) (nema_absf((x) - (y)) <= 0.00001f * nema_min2(nema_absf(x), nema_absf(y)))

/** \brief Доказывает, что равно ли значение x означает
 *
 * \param x значение X
 * \return 1, если x == 0, 0, если x != 0
 *
 */
#define nema_float_is_zero(x) (nema_absf(x) <= 0.00001f)

/** \brief Перевести градусы в радианы
 *
 * \param d Угол в градусах
 * \return Угол в радианах
 *
 */
#define nema_deg_to_rad(d) (0.0174532925199f * (d))  //rad = град*пи/180

/** \brief Перевести радианы в градусы
 *
 * \param r Угол в радианах
 * \return Угол в градусах
 *
 */
#define nema_rad_to_deg(r) (57.295779513f    * (r))  //deg = рад * 180/пи

/** \brief Преобразование целого числа в фиксированную точку 16,16
 *
 * \param — значение для преобразования
 * \return 16.16 значение фиксированной точки
 *
 */
#define nema_i2fx(a)   ((a)*0x10000)

/** \brief Преобразование числа с плавающей запятой в фиксированную точку 16,16.
 *
 * \param — значение для преобразования
 * \return 16.16 значение фиксированной точки
 *
 */
// #definenema_f2fx(a) ((int)(((a)*((float)0x10000)+0.5f)))
int nema_f2fx(float f); //   ((int)(((a)*((float) 0x10000 )+0.5f)))

/** \краткое назначение пола
 *
 * \param a, которое необходимо оценить
 * \return минимальное значение
 *
 */
#define nema_floor(f) ((int)(f) - ( (int)(f) > (f) ))

/** \краткое назначение потолка
 *
 * \param, значение которого должно быть ограничено
 * \возврат максимального значения
 *
 */
#define nema_ceil(f)  ((int)(f) + ( (int)(f) < (f) ))

/** \краткая функция усечения
 *
 * \param x, которое нужно усечь
 * \вернуть усеченное значение
 *
 */
#define nema_truncf(x) (x < 0.0f ? nema_ceil(x) : nema_floor(x))

/** \краткая функция Float Modulo
 *
 * \param x Дивиденд
 * \параметры и делитель
 * \return Остаток
 *
 */
#define nema_fmod(x, y) ( (x) - nema_truncf( ( (x) / (y) ) ) * (y) )

